// Vite config for the mobile UI. Run `npm run build:web` to write
// src/web/dist/; the Node server (src/index.js) serves that directory
// at /web/. The dev script (`npm run dev:web`) starts Vite on :5173
// with HMR for optional browser-side development; the Node server is
// not involved in that path.
import { defineConfig } from 'vite';
import preact from '@preact/preset-vite';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const __dirname = dirname(fileURLToPath(import.meta.url));

// Tiny Vite plugin: emit dist/sw.js from build/sw-src.js with a
// content-hashed cache version baked in. The plugin runs at the
// `generateBundle` stage so Vite has already prepared the dist
// directory. The SW doesn't precache the hashed JS/CSS asset
// filenames — those vary per build and are picked up by the
// cache-first branch the first time the page loads.
function mouaifServiceWorkerPlugin() {
  return {
    name: 'mouaif-service-worker',
    apply: 'build',
    generateBundle() {
      const src = readFileSync(resolve(__dirname, 'build', 'sw-src.js'), 'utf8');
      // Cache version = first 8 hex chars of sha256 of the source
      // body. Every change to the SW source bumps the version,
      // which the activate handler uses to evict the old cache.
      const hash = createHash('sha256').update(src).digest('hex').slice(0, 8);
      const body = src.replace('__CACHE_VERSION__', hash);
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: body });
    }
  };
}

export default defineConfig({
  // The config lives in src/web/ itself, so the project root for
  // Vite is the config file's directory. We resolve it to an
  // absolute path because Vite resolves `root` relative to the
  // config file's location when the config is passed via
  // --config from the project root: a relative `root: 'src/web'`
  // was double-prefixed to src/web/src/web/ (which doesn't exist)
  // and a relative `root: '.'` resolved against the CWD (the
  // project root) instead of the config directory. An absolute
  // path makes the resolution independent of where the user ran
  // the build from.
  root: __dirname,
  base: '/web/',
  // public/ holds the PWA manifest and the icon PNGs. Vite copies
  // its contents verbatim into dist/ at build time, so the
  // resulting bundle URL for the manifest is /web/manifest.webmanifest
  // and the icons live at /web/icons/*.png — matching the absolute
  // paths declared in the manifest itself.
  publicDir: 'public',
  plugins: [preact(), mouaifServiceWorkerPlugin()],
  build: {
    outDir: resolve(__dirname, 'dist'),
    emptyOutDir: true,
    sourcemap: false,
    target: 'es2020',
    rollupOptions: {
      output: {
        // Hash EVERY emitted file, including the entry bundle. Previously
        // the entry was a fixed `assets/index.js`: after a rebuild the URL
        // was unchanged, so browsers (and any intermediate cache) happily
        // served the stale JS while the hashed CSS updated — the UI looked
        // half-broken (e.g. the provider OAuth form not switching) even
        // though the code on disk was fixed. Hashing the entry name makes
        // the URL change on every content change, so a plain reload always
        // fetches the current bundle. index.html is regenerated by Vite
        // with the correct hashed <script> src, so nothing hard-codes the
        // old name.
        entryFileNames: 'assets/index-[hash].js',
        chunkFileNames: 'assets/index-[hash].js',
        assetFileNames: 'assets/index-[hash][extname]'
      }
    }
  },
  server: {
    port: 5173,
    strictPort: false
  }
});
