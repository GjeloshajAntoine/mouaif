'use strict';
// Messages — per-chat transcript.
//
// Each chat (identified by its project directory + chat id) owns a
// transcript of user / assistant / system / tool messages. Messages are
// persisted in the app-level SQLite store (~/.mouaif/store.sqlite) via
// src/chatdb.js. The legacy file backend (`.mouaif.messages.<chatId>.json`)
// was removed; opt-in commit history is available through the per-chat
// trace-to-file export (docs/decisions.md §5).
//
// Schema (per message):
//   { role, content, ts, clientId?, attachments?, reasoning?, usage?, cost?,
//     streamingMs?, modelId?, toolCallId?, name?, args?, ok?, phase? }
//
// `clientId` is the row's identity BEFORE it has a seq. The chat UI draws
// some rows before the server saves them (the user bubble, each streamed
// assistant segment, a stream error card); the id is generated by whichever
// side creates the row first, stored here, and echoed back so the UI can
// swap its unsaved copy for the saved one by id instead of guessing by
// position or content. See docs/features/chat-client-row-ids.md.
const path = require('path');
const toolFeedback = require('./toolFeedback.js');
const CHAT_ID_RE = /^[a-f0-9]{8}$/i;
function assertChatId(chatId) {
if (!chatId || typeof chatId !== 'string' || !CHAT_ID_RE.test(chatId)) {
const e = new Error('chatId must be an 8-character hexadecimal id');
e.code = 'EBADINPUT';
throw e;
}
return chatId;
}
function messagesFilePath(projectDir, chatId) {
if (!projectDir || typeof projectDir !== 'string') {
throw new TypeError('projectDir must be a non-empty string');
}
assertChatId(chatId);
return path.join(projectDir, '.mouaif.messages.' + chatId + '.json');
}
const VALID_ROLES = new Set(['user', 'assistant', 'system', 'tool']);
// Client row ids are opaque, bounded, and URL/selector-safe.
const CLIENT_ID_RE = /^[A-Za-z0-9_-]{1,64}$/;
function normalizeClientId(value) {
return typeof value === 'string' && CLIENT_ID_RE.test(value) ? value : '';
}
// newClientId(prefix) -> string
//
// A fresh row id for a row the SERVER creates first (assistant segments,
// persisted stream errors). Random, not a counter: a counter resets on
// restart and would hand out ids a previous run already used.
function newClientId(prefix) {
return (prefix || 's') + '_' + require('crypto').randomBytes(9).toString('base64url');
}
const MAX_IMAGE_ATTACHMENTS = 8;
const MAX_IMAGE_DATA_URL_CHARS = 12 * 1024 * 1024;
function normalizeAttachments(list) {
if (!Array.isArray(list)) return [];
const out = [];
for (const a of list) {
if (!a || typeof a !== 'object') continue;
if (a.type !== 'image') continue;
const mimeType = typeof a.mimeType === 'string' ? a.mimeType : '';
const dataUrl = typeof a.dataUrl === 'string' ? a.dataUrl : '';
if (!/^image\/(png|jpe?g|webp|gif)$/i.test(mimeType)) continue;
if (!dataUrl.startsWith('data:' + mimeType + ';base64,')) continue;
if (dataUrl.length > MAX_IMAGE_DATA_URL_CHARS) continue;
const item = { type: 'image', mimeType, dataUrl };
if (typeof a.name === 'string' && a.name) item.name = a.name.slice(0, 160);
out.push(item);
if (out.length >= MAX_IMAGE_ATTACHMENTS) break;
}
return out;
}
// Where a user message came from. Only a prompt mouaif itself started carries
// one: a recurring task's run { kind: 'schedule', scheduleId, run }, a
// webhook call's run { kind: 'webhook', hookId, eventId, run } or a hook's
// follow-up { kind: 'hook', hookId, depth, run } (run counts from 1).
function normalizeOrigin(o) {
if (!o || typeof o !== 'object') return null;
const run = Number.isSafeInteger(o.run) && o.run > 0 ? o.run : null;
if (!run) return null;
if (o.kind === 'schedule') {
if (typeof o.scheduleId !== 'string' || !o.scheduleId) return null;
return { kind: 'schedule', scheduleId: o.scheduleId.slice(0, 80), run };
}
if (o.kind === 'webhook') {
if (typeof o.hookId !== 'string' || !o.hookId || typeof o.eventId !== 'string' || !o.eventId) return null;
return { kind: 'webhook', hookId: o.hookId.slice(0, 80), eventId: o.eventId.slice(0, 80), run };
}
// A follow-up turn a `turn.end` hook started (src/hookTurns.js); `depth` is
// its place in the chain (1..3) and doubles as `run`.
if (o.kind === 'hook') {
if (typeof o.hookId !== 'string' || !o.hookId) return null;
return { kind: 'hook', hookId: o.hookId.slice(0, 40), depth: run, run };
}
return null;
}
// What hooks did to a row (src/hooks.js): { notes: [note], context?: string }.
// Notes are display data for the transcript chip; `context` is the labelled
// block the model saw, replayed upstream so later turns see the same history.
const MAX_HOOK_NOTES = 12;
function normalizeHooksMeta(h) {
if (!h || typeof h !== 'object' || Array.isArray(h)) return null;
const out = {};
if (Array.isArray(h.notes)) {
const notes = [];
for (const n of h.notes.slice(0, MAX_HOOK_NOTES)) {
if (!n || typeof n !== 'object' || typeof n.hook !== 'string') continue;
const note = { hook: n.hook.slice(0, 82), event: String(n.event || '').slice(0, 20), decision: String(n.decision || '').slice(0, 12) };
if (typeof n.name === 'string') note.name = n.name.slice(0, 80);
if (typeof n.reason === 'string') note.reason = n.reason.slice(0, 2000);
if (typeof n.error === 'string') note.error = n.error.slice(0, 600);
if (typeof n.notice === 'string') note.notice = n.notice.slice(0, 300);
if (Number.isFinite(n.ms)) note.ms = Math.round(n.ms);
if (n.changedArgs === true) {
note.changedArgs = true;
// Per-key before/after text (src/hooks.js argChanges); `before` is the
// whole earlier argument object kept by rows saved before the diff.
if (Array.isArray(n.changes)) {
note.changes = n.changes.slice(0, 40).filter((c) => c && typeof c.key === 'string').map((c) => {
const change = { key: c.key.slice(0, 128) };
if (typeof c.before === 'string') change.before = c.before.slice(0, 2001);
if (typeof c.after === 'string') change.after = c.after.slice(0, 2001);
return change;
});
} else if (n.before && typeof n.before === 'object') note.before = n.before;
}
if (n.context === true) note.context = true;
if (n.redacted === true) note.redacted = true;
if (n.scope === 'chat' || n.scope === 'project') note.scope = n.scope;
if (typeof n.extension === 'string') note.extension = n.extension.slice(0, 40);
notes.push(note);
}
if (notes.length) out.notes = notes;
}
if (typeof h.context === 'string' && h.context) out.context = h.context.slice(0, 16 * 1024);
// tool.after redaction: which hooks redacted the result for the model, and
// the text the model saw, which replay sends instead of the stored result.
if (h.redacted && typeof h.redacted === 'object' && Array.isArray(h.redacted.by)) {
out.redacted = { by: h.redacted.by.filter((x) => typeof x === 'string').slice(0, 8).map((x) => x.slice(0, 40)), withheld: h.redacted.withheld === true };
if (typeof h.modelContent === 'string') out.modelContent = h.modelContent.slice(0, 4 * 1024 * 1024);
}
return Object.keys(out).length ? out : null;
}
function normalizeMessage(m) {
if (!m || typeof m !== 'object') return null;
if (!VALID_ROLES.has(m.role)) return null;
if (typeof m.content !== 'string') return null;
const out = {
role: m.role,
content: m.content,
ts: typeof m.ts === 'string' ? m.ts : new Date().toISOString()
};
// Preserve a previously-assigned seq (appended rows carry one).
if (typeof m.seq === 'number' && Number.isFinite(m.seq)) out.seq = m.seq;
const clientId = normalizeClientId(m.clientId);
if (clientId) out.clientId = clientId;
if (m.role === 'user') {
const attachments = normalizeAttachments(m.attachments);
if (attachments.length) out.attachments = attachments;
const origin = normalizeOrigin(m.origin);
if (origin) out.origin = origin;
}
if (m.role === 'user' || m.role === 'tool') {
const hooks = normalizeHooksMeta(m.hooks);
if (hooks) out.hooks = hooks;
}
if (m.role === 'assistant') {
if (typeof m.reasoning === 'string') out.reasoning = m.reasoning;
if (m.usage && typeof m.usage === 'object') out.usage = m.usage;
if (m.cost && typeof m.cost === 'object') out.cost = m.cost;
if (typeof m.streamingMs === 'number') out.streamingMs = m.streamingMs;
if (typeof m.modelId === 'string') out.modelId = m.modelId;
}
if (m.role === 'tool') {
if (typeof m.toolCallId === 'string') out.toolCallId = m.toolCallId;
if (typeof m.name === 'string') out.name = m.name;
if (m.args && typeof m.args === 'object') out.args = m.args;
if (typeof m.ok === 'boolean') out.ok = m.ok;
if (typeof m.phase === 'string') out.phase = m.phase;
}
return out;
}
