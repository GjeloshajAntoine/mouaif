// Regression tests for direct @ invocation parsing.
import { buildDirectMcpCall, findCustomActionInvocation, parseAtInvocation, parseDirectRestartInvocation, parseToolArgs, sameCustomActions } from '../frontend/src/components/chat/tools.js';

let pass = 0;
let fail = 0;
function test(name, condition, actual) {
if (condition) {
pass++;
console.log('  ok  - ' + name);
} else {
fail++;
console.log('  FAIL- ' + name + ' :: ' + JSON.stringify(actual));
}
}

const plain = parseAtInvocation('@test ');
test('custom-action invocation keeps its id and empty args',
plain && plain.toolName === 'test' && plain.rest === '', plain);
const actions = [{ id: 'test', label: 'Run tests' }];
test('complete custom-action invocation resolves for direct Enter dispatch',
findCustomActionInvocation('@TEST ', actions) === actions[0],
findCustomActionInvocation('@TEST ', actions));
test('custom actions with ad-hoc args do not direct-dispatch',
findCustomActionInvocation('@test extra', actions) === null,
findCustomActionInvocation('@test extra', actions));

const picker = parseAtInvocation('@mcp__fs__read:path=`/etc/my file` recursive=true');
test('picker colon syntax separates the MCP tool name',
picker && picker.toolName === 'mcp__fs__read', picker);
test('picker colon syntax restores the first key=value argument',
picker && picker.rest === 'path=`/etc/my file` recursive=true', picker);

const args = parseToolArgs(picker && picker.rest);
test('backtick values generated by the picker preserve spaces',
args && args.path === '/etc/my file' && args.recursive === 'true', args);
const directMcpBody = buildDirectMcpCall({
projectDir: '/project', chatId: 'chat-1', callId: 'call-1',
serverId: 'server-1', toolName: 'read', args
});
test('direct MCP calls include authorization and server identifiers',
directMcpBody.projectDir === '/project' && directMcpBody.chatId === 'chat-1' &&
directMcpBody.callId === 'call-1' && directMcpBody.serverId === 'server-1' &&
directMcpBody.toolName === 'read', directMcpBody);

test('JSON arguments still parse',
JSON.stringify(parseToolArgs('{"path":"/tmp","recursive":true}')) === '{"path":"/tmp","recursive":true}',
parseToolArgs('{"path":"/tmp","recursive":true}'));

test('non-invocation text is rejected', parseAtInvocation('check @test') === null,
parseAtInvocation('check @test'));
const restart = parseDirectRestartInvocation('@restart_app');
test('the bare restart command dispatches without a model round-trip',
restart !== null && Object.keys(restart).length === 0, restart);
test('trailing text after the restart command is not direct-dispatched',
parseDirectRestartInvocation('@restart_app apply the latest fix') === null,
parseDirectRestartInvocation('@restart_app apply the latest fix'));
test('the old @-picker reason form is not direct-dispatched',
parseDirectRestartInvocation('@restart_app:reason=`apply the latest fix` ') === null,
parseDirectRestartInvocation('@restart_app:reason=`apply the latest fix` '));
test('a bare reason= pair is not direct-dispatched',
parseDirectRestartInvocation('@restart_app reason="reload"') === null,
parseDirectRestartInvocation('@restart_app reason="reload"'));
test('an unknown restart argument is not direct-dispatched',
parseDirectRestartInvocation('@restart_app:delay=`5`') === null,
parseDirectRestartInvocation('@restart_app:delay=`5`'));
test('a longer tool name is not the restart command',
parseDirectRestartInvocation('@restart_appx now') === null,
parseDirectRestartInvocation('@restart_appx now'));
test('restart mention in normal prose is not direct-dispatched',
parseDirectRestartInvocation('please use @restart_app') === null,
parseDirectRestartInvocation('please use @restart_app'));

// sameCustomActions: the cheap compare behind state._setCustomActions.
const cli = { id: 'test', label: 'Run tests', description: '', kind: 'cli', command: 'npm test' };
const mcp = { id: 'shot', label: 'shot', description: '', kind: 'mcp', serverId: 's', toolName: 't', args: { a: 1 } };
test('equal action lists from separate fetches compare equal',
sameCustomActions([cli, mcp], [{ ...cli }, { ...mcp, args: { a: 1 } }]), null);
test('empty lists compare equal', sameCustomActions([], []), null);
test('a changed label is a difference',
!sameCustomActions([cli], [{ ...cli, label: 'Tests' }]), null);
test('a changed command is a difference',
!sameCustomActions([cli], [{ ...cli, command: 'npm run lint' }]), null);
test('changed mcp args are a difference',
!sameCustomActions([mcp], [{ ...mcp, args: { a: 2 } }]), null);
test('a reordered list is a difference',
!sameCustomActions([cli, mcp], [mcp, cli]), null);
test('a different length is a difference',
!sameCustomActions([cli], [cli, mcp]), null);

console.log('\n' + pass + ' passed, ' + fail + ' failed');
process.exit(fail ? 1 : 0);
